// Emit src/features/beasts/sprites.gen.ts — a static require() map of every
// generated beast sprite (React Native's bundler needs literal require paths),
// plus element+noun and element fallbacks so ANY beast resolves to a sprite.
// Self-contained: scans assets/beasts/*.jpg against genesis.json. Re-run after
// gen-sprites.mjs to pick up newly generated art.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const genesis = JSON.parse(fs.readFileSync(path.join(here, '..', 'out', 'genesis.json'), 'utf8'))
const spriteDir = path.join(here, '..', '..', 'assets', 'beasts')
const present = new Set(fs.readdirSync(spriteDir).filter((f) => f.endsWith('.jpg')).map((f) => f.replace('.jpg', '')))

const noun = (name) => name.split(' ').pop().toLowerCase()
const seeds = []
const species = {}
const element = {}
for (const b of genesis) {
  if (!present.has(b.seed)) continue
  seeds.push(b.seed)
  const sp = `${b.element}-${noun(b.name)}`
  if (!species[sp]) species[sp] = b.seed
  if (!element[b.element]) element[b.element] = b.seed
}

let ts = '// AUTO-GENERATED by nft/src/emit-sprite-module.mjs — do not edit by hand.\n'
ts += '// Pixel-art sprites for the Genesis beasts (Pollinations flux), keyed by seed\n'
ts += '// with element-species + element fallbacks so every beast resolves to art.\n'
ts += '/* eslint-disable */\n'
ts += 'export const SPRITES: Record<string, number> = {\n'
for (const s of seeds) ts += `  '${s}': require('../../../assets/beasts/${s}.jpg'),\n`
ts += '}\n'
ts += `export const SPECIES: Record<string, string> = ${JSON.stringify(species)}\n`
ts += `export const ELEMENT: Record<string, string> = ${JSON.stringify(element)}\n`

const outFile = path.join(here, '..', '..', 'src', 'features', 'beasts', 'sprites.gen.ts')
fs.writeFileSync(outFile, ts)
console.log(`Emitted ${seeds.length} sprites, ${Object.keys(species).length} species, ${Object.keys(element).length} elements → ${outFile}`)
